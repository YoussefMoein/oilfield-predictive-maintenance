md("""
## 11. Limitations and business reading

**Limitations**

* **Synthetic data.** None of these results is evidence about real equipment. The simulator has
  three degradation modes, instant sensor response and no sensor drift; reality has more of
  everything.
* **Failure frequency is inflated** (about 2.5 failures per unit-year) to give enough events. Real
  fleets fail far less often, which makes both learning and evaluation harder.
* **Few events.** The test period contains only a few dozen failures, so event-level figures move by
  several points if one or two failures change. The confidence intervals and the replication table
  are the honest summary, not any single number.
* **Development contamination.** Test-period scores were looked at while debugging the feature
  pipeline. The fresh-seed replication exists to give an estimate that is free of that.
* **The modeller wrote the simulator.** Feature ideas were informed by knowing how the data was made.
* **Scores are not probabilities** and thresholds would need re-setting for any real deployment.
* **No causal claims.** Feature importance describes the model, not the machine.

**How this kind of analysis could support maintenance work** - framed as possibilities, with no
claimed savings or downtime reduction, because none were measured:

* *Inspection prioritisation* - a short, ranked list with the sensor evidence behind each entry.
* *Maintenance planning* - visibility of units trending away from their own baseline between
  scheduled preventive work.
* *Equipment monitoring* - unit-relative, condition-adjusted indicators instead of one fixed alarm
  limit for dissimilar machines.
* *Operational reporting* - a consistent weekly view of how many units sit in each category.

See `reports/model_evaluation_report.md` and `reports/business_analysis.md` for the full discussion.
""")


